"""Evaluate a trained regional graph autoencoder on daily GLORYS fields.

The launcher reads the selected training lap's configuration, archives its
checkpoint, and splits the requested evaluation dates into contiguous daily
intervals. Unset date endpoints use the GLORYS default test split.

Each worker reads and standardizes one interval of ocean and ice fields. It
also loads and standardizes daily atmospheric forcing if the checkpoint
requires it. The worker replaces nonfinite model inputs with zeros while
keeping the original standardized target for scoring.

For each day and channel, the worker computes standardized mean squared error
and a histogram of signed target-minus-prediction errors in physical units.
Both metrics use finite target cells inside the model domain with positive
training mask. A channel with no valid cells has NaN mean squared
error. The first worker also saves a dated target and prediction pair in
standardized units.

The CPU merge validates each shard's dates, row counts, and field layouts.
It copies the results in chronological order into a temporary HDF5 file and
publishes it as errors.h5 after the file closes. The representative pair is
saved as sample.h5. The delete_tmp setting controls cleanup after the merge.

This script was generated by AI based on the changes to train.py and dump.py
in appa2 relative to APPA.
"""

import shutil
import sys
from pathlib import Path

import dask
import h5py
import numpy as np
import torch
import wandb
from dawgz import after, job, schedule
from einops import rearrange
from omegaconf import OmegaConf

from appa2.config.hydra import compose
from appa2.data.const import (
    ATM_FORCING_VARIABLES,
    CONTEXT_VARIABLES,
    GLORYS_DATASET_DATES_TEST,
    OCEAN_VARIABLES,
    STATE_VARIABLES,
    SURFACE_VARIABLES,
)
from appa2.data.data_config import get_dataset_specs
from appa2.data.dataloaders import get_dataloader
from appa2.data.transforms import StandardizeTransform
from appa2.date import get_date_features, split_daily_interval
from appa2.losses import get_area_weights, get_weights
from appa2.save import load_auto_encoder


def signed_error_histograms(error, mask, bin_ranges, multipliers, num_bins):
    """Compute physical-unit target-minus-prediction histograms for every frame."""
    frames, _, channels = error.shape
    counts = torch.empty(frames, channels, num_bins)
    edges = torch.empty(frames, channels, num_bins + 1)
    for frame in range(frames):
        for channel, (bounds, multiplier) in enumerate(zip(bin_ranges, multipliers)):
            values = error[frame, :, channel][mask[frame, :, channel]] * multiplier
            counts[frame, channel], edges[frame, channel] = torch.histogram(
                values, bins=num_bins, range=bounds
            )
    return counts, edges


@torch.no_grad()
def evaluate_chunk(config, train_config, specs, model_path, interval, shard_path, sample_path):
    dask.config.set(scheduler="synchronous")
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    ae = load_auto_encoder(model_path, model_name="model", device=device).to(device).eval()
    has_forcing = train_config.ae.get("forcing_grid") is not None
    forcing_variables = ATM_FORCING_VARIABLES if has_forcing else []

    standardize = StandardizeTransform(
        config.get("state_stats_path") or specs.path_stat_state,
        state_variables=STATE_VARIABLES,
        forcing_variables=forcing_variables if len(forcing_variables)>0 else None,
        depths=specs.depth_levels,
        depth_dim_name=specs.depth_dim_name,
    )

    dataset = specs.dataset(
        state_variables_path=specs.state_variables_path,
        start_date=interval[0],
        end_date=interval[1],
        trajectory_size=1,
        surface_variables=SURFACE_VARIABLES,
        depth_variables=OCEAN_VARIABLES,
        context_variables=CONTEXT_VARIABLES,
        forcing_variables=forcing_variables,
        forcing_path=config.get("forcing_path") or specs.forcing_path,
        context_path=specs.context_path,
        depths=specs.depth_levels,
        transform=standardize,
        fill_nans=False,
    )
    loader = get_dataloader(
        dataset, batch_size=config.batch_size, num_workers=config.num_workers,
        prefetch_factor=1 if config.num_workers else None, shuffle=False,
    )

    loss = train_config.loss
    weights = get_weights(
        specs.grid, SURFACE_VARIABLES, OCEAN_VARIABLES,
        area_per_grid=get_area_weights(specs.grid) if loss.latitude_weighting else None,
        level_weighting=loss.level_weighting,
        surface_variable_weights=loss.get("surface_variable_weights"),
        depth_variable_weights=loss.get("depth_variable_weights"),
        bathymetry_mask=specs.bathymetry_mask,
        levels=specs.depth_levels,
        level_weighting_method=loss.get("level_weighting_method", "grid_size"),
        decay_scale=loss.get("decay_scale"),
    )
    support = (weights.T > 0).to(device) & ae.polar_mask[:, None]
    del weights
    channel_names = SURFACE_VARIABLES + [
        variable for variable in OCEAN_VARIABLES for _ in specs.depth_levels
    ]
    bin_ranges = [tuple(config.bin_ranges[name]) for name in channel_names]
    multipliers = [config.multipliers.get(name, 1.0) for name in channel_names]
    num_rows = len(dataset)
    channels = len(channel_names)
    offset = 0
    with h5py.File(shard_path, "w") as shard:
        shard.create_dataset("dates", (num_rows, 4), "int32")
        shard.create_dataset("std_mse", (num_rows, 1, channels), "float32")
        shard.create_dataset(
            "signed_errors_histograms", (num_rows, channels, config.num_bins), "float32"
        )
        shard.create_dataset(
            "signed_errors_bin_edges", (num_rows, channels, config.num_bins + 1), "float32"
        )
        for batch in loader:
            state, context, timestamp = batch[:3]
            batch_size, steps, _, lat, lon = state.shape
            target = rearrange(state.to(device, dtype=torch.float32), specs.rearange_protocol)
            context = rearrange(context.to(device, dtype=torch.float32), specs.rearange_protocol)
            dates = rearrange(timestamp, "B T D -> (B T) D")
            forcing = None
            if has_forcing:
                forcing = rearrange(
                    batch[3].to(device, dtype=torch.float32), specs.rearange_protocol
                )
                forcing = torch.where(torch.isfinite(forcing), forcing, 0.0)

            finite = torch.isfinite(target)
            model_input = torch.where(finite, target, 0.0)
            context = torch.where(torch.isfinite(context), context, 0.0)
            _, pred = ae(model_input, dates.to(device), context, forcing)
            mask = finite & support
            error = torch.where(mask, target - pred.float(), 0.0)
            mse = error.square().sum(dim=1) / mask.sum(dim=1)
            physical_error = error.cpu() * standardize.state_std.reshape(-1)
            counts, edges = signed_error_histograms(
                physical_error, mask.cpu(), bin_ranges, multipliers, config.num_bins
            )

            rows = slice(offset, offset + batch_size)
            shard["dates"][rows] = dates.numpy()
            shard["std_mse"][rows] = mse.reshape(batch_size, steps, channels).cpu().numpy()
            shard["signed_errors_histograms"][rows] = counts.numpy()
            shard["signed_errors_bin_edges"][rows] = edges.numpy()
            if sample_path is not None and offset == 0:
                pred_grid = rearrange(pred, "(B T) (Y X) C -> B T C Y X",
                                      B=batch_size, T=steps, Y=lat, X=lon)
                with h5py.File(sample_path, "w") as sample:
                    sample["gt"] = state[0].numpy()
                    sample["pred"] = pred_grid[0].cpu().numpy()
                    sample["dates"] = timestamp[0].numpy()
            offset += batch_size

        if offset != num_rows:
            raise ValueError(f"{shard_path.name} expected {num_rows} rows but wrote {offset}.")


def merge_errors(config, intervals, tmp_dir, output_path):
    """Validate the daily shards and publish the merged errors."""
    layouts = {}
    row_counts = []
    for rank, (start, end) in enumerate(intervals):
        days = np.arange(
            np.datetime64(start, "D"), np.datetime64(end, "D") + np.timedelta64(1, "D")
        )
        expected = torch.stack([get_date_features(day) for day in days]).numpy()
        with h5py.File(tmp_dir / f"{rank}.h5", "r") as shard:
            if not np.array_equal(shard["dates"][:], expected):
                raise ValueError(f"Shard {rank} dates do not match {start} through {end}.")
            for key in ("dates", "std_mse", "signed_errors_histograms", "signed_errors_bin_edges"):
                field = shard[key]
                layout = (field.shape[1:], field.dtype)
                if field.shape[0] != len(days) or layout != layouts.setdefault(key, layout):
                    raise ValueError(f"Shard {rank} has an unexpected layout for {key}.")
        row_counts.append(len(days))

    partial = output_path / "errors.h5.partial"
    with h5py.File(partial, "w") as merged:
        for key, (shape, dtype) in layouts.items():
            merged.create_dataset(key, (sum(row_counts), *shape), dtype=dtype)
        offset = 0
        for rank, rows in enumerate(row_counts):
            with h5py.File(tmp_dir / f"{rank}.h5", "r") as shard:
                for start in range(0, rows, config.batch_size):
                    stop = min(start + config.batch_size, rows)
                    for key in layouts:
                        merged[key][offset + start : offset + stop] = shard[key][start:stop]
            offset += rows

    shutil.copy2(tmp_dir / "sample.h5", output_path / "sample.h5")
    partial.replace(output_path / "errors.h5")
    if config.delete_tmp:
        shutil.rmtree(tmp_dir)


def run_reconstruction(config):
    model_path = Path(config.model_path)
    train_config = OmegaConf.load(model_path / "config.yaml")
    specs = get_dataset_specs(train_config.grids.main)
    # The third dataset-spec range currently serves qualitative validation.
    test_start, test_end = GLORYS_DATASET_DATES_TEST
    intervals = split_daily_interval(
        config.num_chunks, config.start_date or test_start, config.end_date or test_end
    )

    output_path = model_path / "reconstruction" / (config.id or wandb.util.generate_id())
    tmp_dir = output_path / "tmp"
    archived_model = output_path / "ae"
    tmp_dir.mkdir(parents=True, exist_ok=True)
    archived_model.mkdir(exist_ok=True)
    shutil.copy2(model_path / "config.yaml", archived_model / "config.yaml")
    shutil.copy2(model_path / f"model_{config.checkpoint}.pth", archived_model / "model.pth")
    OmegaConf.save(config, output_path / "config.yaml")

    @job(name="appa2 reconstruction (compute)", array=len(intervals), **config.hardware.latent_chunk)
    def compute(rank: int):
        evaluate_chunk(
            config, train_config, specs, archived_model, intervals[rank],
            tmp_dir / f"{rank}.h5", tmp_dir / "sample.h5" if rank == 0 else None,
        )

    @after(compute)
    @job(name="appa2 reconstruction (merge)", **config.hardware.aggregate)
    def aggregate():
        merge_errors(config, intervals, tmp_dir, output_path)

    options = {"export": "ALL"}
    if config.hardware.get("account") is not None:
        options["account"] = config.hardware.account
    schedule(aggregate, name="appa2 reconstruction", backend=config.hardware.backend, **options)


if __name__ == "__main__":
    config_path = Path(__file__).with_name("configs") / "reconstruction.yaml"
    run_reconstruction(compose(config_path, overrides=sys.argv[1:]))
